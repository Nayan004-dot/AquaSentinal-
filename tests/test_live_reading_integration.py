"""
Integration test verifying that the ESP32-WROOM-32E firmware payload format
is 100% compliant with the AquaSentinel backend ingestion endpoint.
"""
from datetime import datetime, timezone, timedelta
import pytest
from fastapi.testclient import TestClient

from backend.config import Settings
from backend.main import create_app

DEVICE_ID = "AQUASENTINEL-01"
TOKEN = "test-device-secret-not-for-production"


def make_client(tmp_path):
    settings = Settings(
        database_path=str(tmp_path / "test.sqlite3"),
        device_tokens={DEVICE_ID: TOKEN},
        sampling_interval_seconds=10,
        device_stale_after_seconds=120,
    )
    app = create_app(settings, start_aggregation_worker=False)
    return TestClient(app)


def test_esp32_firmware_payload_ingestion(tmp_path):
    """
    Test the exact payload generated by aquasentinel.ino when transmitting
    live readings from TDS, Turbidity, and DS18B20.
    """
    with make_client(tmp_path) as client:
        # 1. Payload as constructed by firmware/aquasentinel.ino
        firmware_payload = {
            "schema_version": "1.0",
            "device_id": DEVICE_ID,
            "sequence": 1,
            "timestamp": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "measurement_point": "outlet",
            "firmware_version": "0.1.0",
            "outlet": {
                "tds": {
                    "value": 142.5,
                    "unit": "ppm",
                    "status": "valid",
                    "calibrated": False
                },
                "ph": {
                    "value": None,
                    "unit": "pH",
                    "status": "unavailable",
                    "calibrated": False
                },
                "turbidity": {
                    "value": 2.145,
                    "unit": "raw",
                    "status": "valid",
                    "calibrated": False
                },
                "temperature": {
                    "value": 25.62,
                    "unit": "C",
                    "status": "valid",
                    "calibrated": True
                }
            }
        }

        # 2. Test ingestion with X-Device-Token authentication
        headers = {
            "Content-Type": "application/json",
            "X-Device-Token": TOKEN
        }
        res = client.post("/api/v1/sensors/outlet", json=firmware_payload, headers=headers)
        assert res.status_code == 201, f"Ingestion failed: {res.text}"
        data = res.json()
        assert data["accepted"] is True
        assert data["device_id"] == DEVICE_ID
        assert data["sequence"] == 1

        # 3. Verify latest reading endpoint
        latest_res = client.get("/api/v1/outlet/latest", params={"device_id": DEVICE_ID})
        assert latest_res.status_code == 200
        latest = latest_res.json()
        assert latest["data_status"] == "available"
        assert latest["measurements"]["tds"]["value"] == 142.5
        assert latest["measurements"]["turbidity"]["value"] == 2.145
        assert latest["measurements"]["temperature"]["value"] == 25.62
        assert latest["measurements"]["ph"]["status"] == "unavailable"

        # 4. Verify history endpoint (within max_history_days limit of 31 days)
        now = datetime.now(timezone.utc)
        from_time = (now - timedelta(hours=2)).strftime("%Y-%m-%dT%H:%M:%SZ")
        to_time = (now + timedelta(hours=1)).strftime("%Y-%m-%dT%H:%M:%SZ")
        history_res = client.get("/api/v1/outlet/history", params={
            "device_id": DEVICE_ID,
            "from": from_time,
            "to": to_time
        })
        assert history_res.status_code == 200, f"History query failed: {history_res.text}"
        items = history_res.json()["items"]
        assert len(items) == 1
        assert items[0]["sequence"] == 1
